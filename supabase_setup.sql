-- KinoZona shared content table and access policies.
-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.kz_content (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('filmas','serialas')),
  title text not null,
  year integer,
  genre text,
  poster_url text,
  video_url text,
  description text,
  seasons integer not null default 0,
  featured boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.kz_content enable row level security;
grant select on public.kz_content to anon, authenticated;
grant insert, update, delete on public.kz_content to authenticated;
drop policy if exists "Public can read KinoZona content" on public.kz_content;
create policy "Public can read KinoZona content" on public.kz_content for select to anon, authenticated using (true);
drop policy if exists "Signed-in admins can add KinoZona content" on public.kz_content;
create policy "Signed-in admins can add KinoZona content" on public.kz_content for insert to authenticated with check (auth.uid() is not null);
drop policy if exists "Signed-in admins can update KinoZona content" on public.kz_content;
create policy "Signed-in admins can update KinoZona content" on public.kz_content for update to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);
drop policy if exists "Signed-in admins can delete KinoZona content" on public.kz_content;
create policy "Signed-in admins can delete KinoZona content" on public.kz_content for delete to authenticated using (auth.uid() is not null);
